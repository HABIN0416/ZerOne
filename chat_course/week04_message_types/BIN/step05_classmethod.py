# │ 클래스 메서드  │ cls = 클래스 자신│ Phone.from_wire(...) ← 객체 없이│
# └───────────────┴──────────────────┴────────────────────────────────┘
# "객체를 만들려는 순간엔 아직 객체가 없다" → 그래서 self 가 아니라 cls 인 것!


