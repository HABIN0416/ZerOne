# -*- coding: utf-8 -*-
"""
Week 6 강의자료(PPT) 생성 스크립트
실행:  python make_ppt.py   →   Week06_방_엉성한버전.pptx
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ppt_theme import Deck

KICKER = "파이썬으로 만드는 실시간 채팅 프로그램"

d = Deck()

# ── 1. 표지 ────────────────────────────────────────────────
d.title(
    kicker=KICKER,
    title="방을 나눠보자 — 일단 엉성하게",
    subtitle="방별 채팅 · 전역 딕셔너리로 시작했더니 상태가 흩어진다",
    notes=(
        "C단계(방) 시작. 오늘은 일부러 '엉성한 버전'을 만든다 — 3주차처럼 의도된 고통.\n"
        "오늘 한 줄 목표: 방이 되긴 하는데, 전역 상태가 여기저기 흩어져 곧 엉킨다는 걸 느끼게 한다.\n"
        "이 엉킴이 다음 주 'Room 객체'의 동기."
    ),
)

# ── 2. 도입 질문 ──────────────────────────────────────────
d.big_question(
    question="단톡방처럼 방을 나누려면?\n다른 방 사람한텐 안 보이게.",
    hint="지금은 한 명이 치면 '전부'에게 갑니다. 방이 생기면 '이 방 사람에게만' 가야겠죠.",
    notes=(
        "지금까지는 모두에게 broadcast 했다. 방이 생기면 대상이 '그 방 멤버'로 좁아진다.\n"
        "이걸 '어디로 보낼지 정하기 = 라우팅'이라고 부른다고 짚어 준다."
    ),
)

# ── 3. 개념: 라우팅 ───────────────────────────────────────
d.bullets(
    "전체에서 → 방 멤버에게만 (라우팅)",
    [
        "지금: 받은 메시지를 접속자 전원에게 broadcast",
        "방이 생기면: '이 방 멤버에게만' 보낸다",
        "라우팅(routing) = 메시지를 어디로 보낼지 결정하는 것",
        "필요한 명령: /create(방 만들기), /join(입장), /leave, /rooms, /who",
    ],
    notes=(
        "라우팅을 어렵게 설명하지 말 것 — '누구에게 보낼지 고르는 일'이면 충분.\n"
        "명령들을 먼저 소개하고, 이걸 어떻게 구현할지로 넘어간다."
    ),
)

# ── 4. 엉성 선언: 전역 딕셔너리 3개 ───────────────────────
d.bullets(
    "일부러 엉성하게 — 전역 딕셔너리로",
    [
        "방·사람·소켓 정보를 전부 전역 변수에 둔다",
        ("rooms      = {방이름: [소켓, ...]}   # 방마다 누가 있나", 1),
        ("nicknames  = {소켓: 닉네임}          # 이 소켓은 누구", 1),
        ("where      = {소켓: 방이름}          # 지금 어느 방에", 1),
        "돌아가긴 한다. 그런데 정보가 '세 군데'에 흩어져 있다.",
    ],
    notes=(
        "왜 세 개나? 방→사람, 사람→이름, 사람→방을 다 알아야 하기 때문.\n"
        "이렇게 흩어 두면, 상태를 바꿀 때마다 세 군데를 모두 맞춰야 한다(다음 코드에서 확인)."
    ),
)

# ── 5. code: 전역 상태 + 방 브로드캐스트 ──────────────────
d.code(
    "전역 상태와 방 단위 전송",
    "rooms = {}        # 방이름 -> [소켓, ...]\n"
    "nicknames = {}    # 소켓 -> 닉네임\n"
    "where = {}        # 소켓 -> 현재 방이름\n"
    "\n"
    "def room_broadcast(room_name, message):\n"
    "    members = rooms.get(room_name, [])    # 그 방 멤버만\n"
    "    for c in members:\n"
    "        send_to(c, message)",
    caption="broadcast 의 대상이 '전원'에서 '그 방 멤버'로 좁아졌다.",
    notes=(
        "room_broadcast 자체는 단순하다. 문제는 'rooms 를 누가 언제 채우고 비우나'이다(다음 슬라이드).\n"
        "전역 변수 세 개가 한 화면에 나란히 — 이미 좀 불안해 보인다는 점을 짚는다."
    ),
)

# ── 6. code: /join — 세 군데를 다 맞춰야 ──────────────────
d.code(
    "/join 한 번에 — 세 군데를 다 고친다",
    "elif cmd == \"/join\":\n"
    "    old = where.get(conn)\n"
    "    if old and conn in rooms.get(old, []):\n"
    "        rooms[old].remove(conn)     # ① 이전 방에서 빼고\n"
    "    rooms[arg].append(conn)         # ② 새 방에 넣고\n"
    "    where[conn] = arg               # ③ 현재 방 갱신\n"
    "    # 셋 중 하나라도 빠뜨리면 곧바로 버그",
    caption="입장 한 번에 전역 세 군데를 손으로 맞춰야 한다.",
    notes=(
        "①②③ 을 손으로 짚으며 '이걸 매번 다 맞춰야 한다'를 강조.\n"
        "예: ① 을 빠뜨리면 이전 방에 유령으로 남아 양쪽 방에서 메시지를 받는다.\n"
        "이게 전역 상태의 위험 — 변경 지점이 흩어져 있다."
    ),
)

# ── 7. code: 퇴장 정리 — 또 세 군데 ───────────────────────
d.code(
    "퇴장할 때도 — 또 세 군데를 청소",
    "# 손님이 나가면 (연결이 끊기면)\n"
    "room = where.pop(conn, None)               # where 정리\n"
    "if room and conn in rooms.get(room, []):\n"
    "    rooms[room].remove(conn)               # rooms 정리\n"
    "name = nicknames.pop(conn, \"?\")            # nicknames 정리\n"
    "# 하나라도 빠지면 '유령 회원'이 남는다",
    caption="join 에서도, leave 에서도, 끊길 때도 — 같은 세 곳을 매번 청소.",
    notes=(
        "퇴장 처리에서도 똑같이 세 군데를 정리해야 한다. 코드가 곳곳에 흩어져 추적이 어렵다.\n"
        "'유령 회원' 버그를 일부러 만들어 보여 줘도 좋다(rooms 정리 한 줄을 주석 처리)."
    ),
)

# ── 8. 실행 결과 (실제 캡처) ──────────────────────────────
d.terminals(
    "직접 돌려보자 — 두 방이 서로 안 보인다",
    [
        ("잡담방 :  민수",
         "/create 잡담\n"
         "/join 잡담\n"
         "*** 민수님이 입장했습니다 ***\n"
         "*** 영희님이 입장했습니다 ***\n"
         "잡담방에서 안녕!\n"
         "민수: 잡담방에서 안녕!"),
        ("게임방 :  철수",
         "/create 게임\n"
         "/join 게임\n"
         "*** 철수님이 입장했습니다 ***\n"
         "*** 지민님이 입장했습니다 ***\n"
         "게임방 고고!\n"
         "철수: 게임방 고고!"),
        ("게임방 :  지민",
         "/join 게임\n"
         "철수: 게임방 고고!\n"
         "/rooms\n"
         "방 목록: 잡담(2명),\n"
         "         게임(2명)\n"
         "\n"
         "← 민수의 '잡담방' 글은\n"
         "   여기엔 안 온다"),
    ],
    notes=(
        "실제 4개 클라이언트로 캡처한 결과. 잡담방 대화는 게임방에 안 보이고, 그 반대도 마찬가지.\n"
        "/rooms 로 두 방이 다 보이는 것도 시연. /who 로 멤버 확인도.\n"
        "데모는 잘 된다 — 그래서 더, '코드가 왜 불안한지'를 다음 슬라이드에서 정리한다."
    ),
)

# ── 9. 깨달음 (고통 3) ────────────────────────────────────
d.takeaway(
    headline="되긴 되는데, 방·사람·소켓이 전역에 흩어져 곧 엉킨다.",
    points=[
        "상태가 세 군데(rooms/nicknames/where)에 흩어져 있다",
        "join·leave·퇴장마다 그 세 곳을 모두 맞춰야 한다",
        "한 곳만 빠뜨려도 '유령 회원' 같은 버그가 생긴다",
        "다음 주: 방을 'Room 객체'로 묶어 이 엉킴을 없앤다",
    ],
    notes=(
        "오늘도 '해결'이 아니라 '고통의 확인'으로 끝난다(의도된 학습 장치).\n"
        "핵심: 관련된 데이터(방 이름·멤버·기록)가 흩어져 있으면 관리가 어렵다 → 한 덩어리로 묶자(캡슐화).\n"
        "다음 주 예고: Room 객체가 join/leave/post 를 스스로 책임진다."
    ),
)

# ── 10. 빈칸 채우기 — 흩어진 걸 Room 하나로 (스스로 설계) ──
d.table(
    "다음 표를 완성해 보세요 — 이게 Room 클래스 설계의 핵심",
    ["하는 일", "지금 (흩어진 전역)", "Room 클래스라면?"],
    [
        ["방이 가진 것", "rooms[이름] = [소켓들]", "속성: self.name, self.members"],
        ["방에 들어가기", "rooms[방].append(소켓)", "메서드: join(self, 소켓)"],
        ["방에서 나가기", "rooms[방].remove(소켓)", "?"],
        ["그 방에만 보내기", "room_broadcast(방, msg)", "?"],
        ["이 방 멤버 목록", "rooms[방] 의 닉네임들", "?"],
    ],
    col_widths=[2.4, 4.7, 4.7],
    caption="규칙: 흩어진 '데이터'는 속성으로, 그 데이터를 만지던 '함수'는 메서드로.",
    notes=(
        "빈칸 채우기 = 스스로 Room 설계를 '발견'하게 하는 장치. 완성본은 다음 주에 함께 만든다.\n"
        "위 두 줄은 예시로 채워 주고, 아래 세 줄(?)을 학생이 채우게 한다.\n"
        "정답 예: 나가기 → leave(self, 소켓) / 보내기 → post(self, message) / 멤버목록 → who(self).\n"
        "핵심 한 줄: 흩어진 데이터를 한 덩어리(속성)로 모으고, 함수를 그 클래스의 메서드로 옮긴다.\n"
        "→ 4주차 step01 '클래스 = 데이터 + 동작 한 덩어리' 와 그대로 연결된다."
    ),
)

# ── 11. 직접 해보기 ──────────────────────────────────────
d.bullets(
    "직접 해보기",
    [
        "/who 를 개선해 닉네임과 방 이름을 함께 보기 좋게 표시",
        "전역 상태 때문에 생기는 버그 '일부러' 만나보기",
        ("rooms 정리 한 줄을 주석 처리하고 방을 옮겨 보세요 → 유령 회원 발생", 1),
        "빈 방이 되면 자동으로 삭제되게 해보기",
        "(생각) 방 하나에 필요한 정보(이름·멤버·기록)를 한 곳에 모으면 어떨까?",
    ],
    notes=(
        "두 번째 과제(유령 회원 재현)가 핵심 — 전역 상태의 위험을 몸으로 느끼게 한다.\n"
        "마지막 생각거리가 다음 주 Room 객체의 직접적 씨앗.\n"
        "제출물은 다음 주 도입에서 함께 풀이."
    ),
)

out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "Week06_방_엉성한버전.pptx")
d.save(out)
print("저장 완료:", out)
print("슬라이드 수:", len(d.prs.slides._sldIdLst))
